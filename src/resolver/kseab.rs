//! Resolver for KSEAB/KSEEB SSLC question papers.
//!
//! Recent KSEAB pages expose downloads through ASP.NET postbacks, which do not
//! provide stable GET URLs. The resolver follows static index pages and only
//! emits entries with direct PDF URLs; postback-only pages are reported as
//! warnings in the crawl report.

use std::collections::{HashSet, VecDeque};
use std::time::Duration;

use reqwest::Client;
use scraper::{Html, Selector};
use url::Url;

use super::{
    clean_text, extract_year, fetch_html, fetch_optional_html, infer_material_type, is_pdf_url,
    language_from_text, parse_document, resolve_url, Resolved, SourceDefinition,
};
use crate::catalog::{Entry, MaterialType};
use crate::error::ResolverResult;

/// A year/exam subpage linked from the SSLC question-paper index.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SeriesPage {
    /// Page URL.
    pub url: Url,
    /// Exam year parsed from the link text.
    pub year: u16,
    /// Link text.
    pub title: String,
    /// Whether this is a model-answer/marking-scheme page.
    pub model_answers: bool,
}

/// Follow year pages and parse direct PDF links.
pub async fn resolve(client: &Client, source: &SourceDefinition) -> ResolverResult<Resolved> {
    let base = source.base_url()?;
    let index = fetch_html(client, &base).await?;

    let mut resolved = Resolved {
        pages_fetched: 1,
        ..Resolved::default()
    };

    let mut queue: VecDeque<SeriesPage> = parse_index(&index, &base, &source.year_range).into();
    let mut visited = HashSet::new();
    visited.insert(base.to_string());

    if queue.is_empty() {
        resolved.note(format!(
            "{base}: no SSLC question-paper year links found in the year range"
        ));
    }

    let mut postback_pages = 0_usize;

    while let Some(series) = queue.pop_front() {
        if resolved.pages_fetched >= source.max_pages {
            resolved.note(format!(
                "stopped after {} pages (max_pages = {})",
                resolved.pages_fetched, source.max_pages
            ));
            break;
        }

        if !visited.insert(series.url.to_string()) {
            continue;
        }

        match fetch_optional_html(client, &series.url).await {
            Ok(Some(html)) => {
                resolved.pages_fetched += 1;

                if series.model_answers {
                    let entries = parse_model_answer_page(&html, &series.url, series.year, source);
                    if entries.is_empty() {
                        resolved.note(format!(
                            "{}: model-answer page contained no direct PDF links",
                            series.url
                        ));
                    }
                    resolved.entries.extend(entries);
                } else {
                    let (entries, postback_only) =
                        parse_question_page(&html, &series.url, series.year, &series.title, source);

                    if postback_only {
                        postback_pages += 1;
                        resolved.note(format!(
                            "{}: downloads are generated by ASP.NET postbacks, so no stable direct PDF URL exists",
                            series.url
                        ));
                    } else if entries.is_empty() {
                        resolved.note(format!(
                            "{}: page contained no direct PDF links",
                            series.url
                        ));
                    }

                    resolved.entries.extend(entries);

                    for child in parse_index(&html, &series.url, &source.year_range) {
                        if !visited.contains(&child.url.to_string()) {
                            queue.push_back(child);
                        }
                    }
                }

                for model in parse_model_answer_links(&html, &series.url, &source.year_range) {
                    if !visited.contains(&model.url.to_string()) {
                        queue.push_back(model);
                    }
                }
            }
            Ok(None) => {
                resolved.note(format!("{}: HTTP 404", series.url));
            }
            Err(error) => {
                resolved.note(format!("{}: {error}", series.url));
            }
        }

        tokio::time::sleep(Duration::from_millis(150)).await;
    }

    if resolved.entries.is_empty() && postback_pages > 0 {
        resolved.note(
            "KSEAB currently serves recent question papers only through interactive postbacks; \
             older direct links are included when available",
        );
    }

    resolved.dedupe();
    Ok(resolved)
}

/// Find year/exam pages linked from a question-paper index.
#[must_use]
pub fn parse_index(html: &str, page_url: &Url, year_range: &[u16; 2]) -> Vec<SeriesPage> {
    let document: Html = parse_document(html);
    let anchor_selector = Selector::parse("a[href]").expect("static anchor selector");
    let mut pages = Vec::new();
    let mut seen = HashSet::new();

    for anchor in document.select(&anchor_selector) {
        let text = clean_text(&anchor.text().collect::<String>());
        if text.is_empty() {
            continue;
        }

        let lower = text.to_lowercase();
        if !lower.contains("sslc")
            || (!lower.contains("question") && !lower.contains("paper") && !lower.contains(" qp"))
        {
            continue;
        }

        let Some(year) = extract_year(&text) else {
            continue;
        };
        if !(year_range[0]..=year_range[1]).contains(&year) {
            continue;
        }

        let Some(href) = anchor.value().attr("href") else {
            continue;
        };
        let Some(url) = resolve_url(page_url, href) else {
            continue;
        };
        if is_pdf_url(&url) || !seen.insert(url.to_string()) {
            continue;
        }

        pages.push(SeriesPage {
            url,
            year,
            title: text,
            model_answers: false,
        });
    }

    pages
}

/// Find model-answer/marking-scheme pages linked from a question-paper page.
#[must_use]
pub fn parse_model_answer_links(
    html: &str,
    page_url: &Url,
    year_range: &[u16; 2],
) -> Vec<SeriesPage> {
    let document: Html = parse_document(html);
    let anchor_selector = Selector::parse("a[href]").expect("static anchor selector");
    let mut pages = Vec::new();
    let mut seen = HashSet::new();

    for anchor in document.select(&anchor_selector) {
        let Some(href) = anchor.value().attr("href") else {
            continue;
        };

        let text = clean_text(&anchor.text().collect::<String>());
        let haystack = format!("{} {}", text.to_lowercase(), href.to_lowercase());
        if !haystack.contains("model-answer")
            && !haystack.contains("model answer")
            && !haystack.contains("modelanswers")
        {
            continue;
        }

        let Some(url) = resolve_url(page_url, href) else {
            continue;
        };
        if is_pdf_url(&url) || !seen.insert(url.to_string()) {
            continue;
        }

        let Some(year) = extract_year(&haystack) else {
            continue;
        };
        if !(year_range[0]..=year_range[1]).contains(&year) {
            continue;
        }

        pages.push(SeriesPage {
            url,
            year,
            title: if text.is_empty() {
                format!("SSLC {year} Model Answers")
            } else {
                text
            },
            model_answers: true,
        });
    }

    pages
}

/// Parse direct question-paper PDFs from one year/exam page.
///
/// Returns the entries and whether the page appears to be a postback-only
/// ASP.NET grid.
#[must_use]
pub fn parse_question_page(
    html: &str,
    page_url: &Url,
    year: u16,
    series_title: &str,
    source: &SourceDefinition,
) -> (Vec<Entry>, bool) {
    let document: Html = parse_document(html);
    let content_selector = Selector::parse("div.ipage a[href]").expect("static content selector");
    let all_selector = Selector::parse("a[href]").expect("static anchor selector");
    let content_anchors: Vec<_> = document.select(&content_selector).collect();
    let anchors: Vec<_> = if content_anchors.is_empty() {
        document.select(&all_selector).collect()
    } else {
        content_anchors
    };
    let mut entries = Vec::new();
    let mut seen = HashSet::new();

    for anchor in anchors {
        let Some(href) = anchor.value().attr("href") else {
            continue;
        };
        let Some(url) = resolve_url(page_url, href) else {
            continue;
        };
        if !is_pdf_url(&url) || !seen.insert(url.to_string()) {
            continue;
        }

        let text = clean_text(&anchor.text().collect::<String>());
        let filename = url
            .path_segments()
            .and_then(|mut segments| segments.next_back())
            .unwrap_or_default();

        if !is_question_paper(&text, filename) {
            continue;
        }

        let mut kind = infer_material_type(&text);
        if kind == MaterialType::Textbook {
            kind = MaterialType::PreviousYearPaper;
        }

        let subject = infer_subject(&text, filename);
        let language = language_from_text(&format!("{text} {filename}"));
        let mut title = if text.is_empty() {
            format!("SSLC {subject} {year} Question Paper")
        } else {
            text
        };
        if let Some(exam) = exam_label(series_title) {
            title = format!("{title} ({exam})");
        }

        entries.push(Entry {
            level: "SSLC".to_owned(),
            stream: None,
            subject,
            kind,
            title,
            language,
            year: Some(year),
            url: url.to_string(),
            source: source.name.clone(),
            page: Some(page_url.to_string()),
            size_bytes: None,
        });
    }

    let postback_only = entries.is_empty() && html.contains("__doPostBack");
    (entries, postback_only)
}

fn exam_label(series_title: &str) -> Option<&'static str> {
    let lower = series_title.to_lowercase();
    if lower.contains("supplement") {
        Some("Supplementary")
    } else if lower.contains("main") {
        Some("Main")
    } else {
        None
    }
}

fn is_question_paper(text: &str, filename: &str) -> bool {
    let haystack = format!("{text} {filename}").to_lowercase();

    let blocked = [
        "tender",
        "quotation",
        "recruitment",
        "notification",
        "circular",
        "time table",
        "timetable",
        "nmms",
        "admit card",
        "marks card",
        "result",
        "press release",
        "photo",
        "gazette",
    ];
    if blocked.iter().any(|term| haystack.contains(term)) {
        return false;
    }

    haystack.contains("version")
        || haystack.contains("question paper")
        || haystack.contains("questionpaper")
        || haystack.contains("examqp")
        || haystack.contains("_qp")
        || haystack.contains(" qp")
}

fn known_subject(text: &str) -> Option<&'static str> {
    let lower = text.to_lowercase();
    let subjects = [
        ("social science", "Social Science"),
        ("socialscience", "Social Science"),
        ("carnatic/hindustani music", "Carnatic/Hindustani Music"),
        ("mathematics", "Mathematics"),
        ("maths", "Mathematics"),
        ("science", "Science"),
        ("physics", "Physics"),
        ("chemistry", "Chemistry"),
        ("biology", "Biology"),
        ("history", "History"),
        ("geography", "Geography"),
        ("economics", "Economics"),
        ("political science", "Political Science"),
        ("sociology", "Sociology"),
        ("kannada", "Kannada"),
        ("english", "English"),
        ("hindi", "Hindi"),
        ("urdu", "Urdu"),
        ("sanskrit", "Sanskrit"),
        ("marathi", "Marathi"),
        ("telugu", "Telugu"),
        ("tamil", "Tamil"),
        ("arabic", "Arabic"),
        ("persian", "Persian"),
    ];

    subjects
        .into_iter()
        .find(|(needle, _)| lower.contains(needle))
        .map(|(_, subject)| subject)
}

/// Parse direct model-answer PDFs from one marking-scheme page.
#[must_use]
pub fn parse_model_answer_page(
    html: &str,
    page_url: &Url,
    year: u16,
    source: &SourceDefinition,
) -> Vec<Entry> {
    let document: Html = parse_document(html);
    let content_selector = Selector::parse("div.ipage a[href]").expect("static content selector");
    let all_selector = Selector::parse("a[href]").expect("static anchor selector");
    let content_anchors: Vec<_> = document.select(&content_selector).collect();
    let anchors: Vec<_> = if content_anchors.is_empty() {
        document.select(&all_selector).collect()
    } else {
        content_anchors
    };

    let mut entries = Vec::new();
    let mut seen = HashSet::new();

    for anchor in anchors {
        let Some(href) = anchor.value().attr("href") else {
            continue;
        };
        let Some(url) = resolve_url(page_url, href) else {
            continue;
        };
        if !is_pdf_url(&url) || !seen.insert(url.to_string()) {
            continue;
        }

        let text = clean_text(&anchor.text().collect::<String>());
        let filename = url
            .path_segments()
            .and_then(|mut segments| segments.next_back())
            .unwrap_or_default();
        let haystack = format!("{text} {filename}");
        let known = known_subject(&haystack);
        let subject = known.map_or_else(|| infer_subject(&text, filename), str::to_owned);
        let normalised_text = text.to_lowercase();

        if subject == "General"
            || subject
                .chars()
                .all(|character| character.is_ascii_digit() || character.is_whitespace())
            || (known.is_none()
                && matches!(
                    normalised_text.as_str(),
                    "" | "download" | "click here" | "pdf"
                ))
        {
            continue;
        }

        let language = language_from_text(&format!("{text} {filename}"));
        let title = if text.is_empty() {
            format!("SSLC {year} {subject} Model Answer")
        } else if normalised_text.contains("model answer") {
            text
        } else {
            format!("{text} (Model Answer)")
        };

        entries.push(Entry {
            level: "SSLC".to_owned(),
            stream: None,
            subject,
            kind: MaterialType::MarkingScheme,
            title,
            language,
            year: Some(year),
            url: url.to_string(),
            source: source.name.clone(),
            page: Some(page_url.to_string()),
            size_bytes: None,
        });
    }

    entries
}

fn infer_subject(text: &str, filename: &str) -> String {
    let source = if text.is_empty() { filename } else { text };

    if let Some(subject) = known_subject(source) {
        return subject.to_owned();
    }

    let mut cut = source.len();
    for separator in [" - ", " – ", " — ", "–"] {
        if let Some(position) = source.find(separator) {
            cut = cut.min(position);
        }
    }

    let mut subject = clean_text(&source[..cut]);
    for prefix in [
        "First Language ",
        "First Language",
        "Second Language ",
        "Second Language",
    ] {
        if let Some(rest) = subject.strip_prefix(prefix) {
            subject = rest.trim().to_owned();
            break;
        }
    }

    if subject.is_empty() {
        "General".to_owned()
    } else {
        subject
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::resolver::{Registry, SourceDefinition};

    const INDEX: &str = include_str!("../../tests/fixtures/resolvers/kseab_index.html");
    const DIRECT: &str = include_str!("../../tests/fixtures/resolvers/kseab_2022.html");
    const MODEL: &str = include_str!("../../tests/fixtures/resolvers/kseab_model_answers.html");
    const POSTBACK: &str = include_str!("../../tests/fixtures/resolvers/kseab_postback.html");
    const REGISTRY: &str = include_str!("../../sources/registry.toml");

    fn source() -> SourceDefinition {
        Registry::from_toml("registry", REGISTRY)
            .unwrap()
            .find("kseab-sslc-question-papers")
            .unwrap()
            .clone()
    }

    #[test]
    fn parses_year_links() {
        let page =
            Url::parse("https://kseab.karnataka.gov.in/new-page/SSLC%20QUESTION%20PAPERS/en")
                .unwrap();
        let pages = parse_index(INDEX, &page, &[2016, 2026]);

        assert!(pages.len() >= 5);
        assert!(pages.iter().any(|page| page.year == 2026));
        assert!(pages.iter().any(|page| page.year == 2022));
        assert!(pages.iter().all(|page| page.year >= 2016));
    }

    #[test]
    fn parses_direct_question_paper_pdfs() {
        let page = Url::parse(
            "https://kseab.karnataka.gov.in/new-page/2022SSLCMainExaminationQuestionpapers/en",
        )
        .unwrap();
        let (entries, postback) = parse_question_page(
            DIRECT,
            &page,
            2022,
            "March/April 2022 SSLC Main Examination Question Paper",
            &source(),
        );

        assert_eq!(entries.len(), 4);
        assert!(!postback);
        assert!(entries.iter().all(|entry| entry.year == Some(2022)));
        assert!(entries
            .iter()
            .any(|entry| entry.subject == "Mathematics"
                && entry.language == crate::config::Language::Hi));
        assert!(entries.iter().any(|entry| entry.subject == "Social Science"
            && entry.language == crate::config::Language::En));
        assert!(entries.iter().any(|entry| entry.subject == "Mathematics"
            && entry.language == crate::config::Language::Kn
            && entry.title.contains("81 K/E")));
        assert!(entries.iter().any(|entry| entry.title.contains("(Main)")));
        assert!(entries
            .iter()
            .all(|entry| entry.url.starts_with("https://kseab.karnataka.gov.in/")));
        assert!(entries
            .iter()
            .all(|entry| !entry.title.to_lowercase().contains("tender")));
    }

    #[test]
    fn detects_postback_only_pages() {
        let page = Url::parse("https://kseeb.karnataka.gov.in/QP/SSLC2025_EXAM1_QP").unwrap();
        let (entries, postback) = parse_question_page(
            POSTBACK,
            &page,
            2025,
            "SSLC 2025 EXAM-1 QUESTION PAPERS",
            &source(),
        );

        assert!(entries.is_empty());
        assert!(postback);
    }

    #[test]
    fn parses_model_answer_pdfs() {
        let page = Url::parse(
            "https://kseab.karnataka.gov.in/new-page/JUNE%20JULY-2020-SCIENCE%20MODEL-ANSWERS/en",
        )
        .unwrap();
        let entries = parse_model_answer_page(MODEL, &page, 2020, &source());

        assert_eq!(entries.len(), 2);
        assert!(entries
            .iter()
            .all(|entry| entry.kind == MaterialType::MarkingScheme));
        assert!(entries.iter().any(|entry| entry.subject == "Biology"));
        assert!(entries.iter().any(|entry| entry.subject == "Physics"));
        assert!(entries.iter().all(|entry| entry.year == Some(2020)));
    }

    #[test]
    fn discovers_model_answer_pages() {
        let html = r#"
            <a href="https://kseab.karnataka.gov.in/new-page/JUNE%20JULY-2020-SCIENCE%20MODEL-ANSWERS/en">SCIENCE</a>
        "#;
        let page = Url::parse(
            "https://kseab.karnataka.gov.in/new-page/2022SSLCMainExaminationQuestionpapers/en",
        )
        .unwrap();
        let pages = parse_model_answer_links(html, &page, &[2016, 2026]);

        assert_eq!(pages.len(), 1);
        assert_eq!(pages[0].year, 2020);
        assert!(pages[0].model_answers);
    }
}
